// Apply tools/crit-tests-data.mjs to the item JSON sources: each listed critical gets one
// "<Critical> (Test)" effect whose immediate script prompts the Test and applies the outcome.
// Idempotent: re-running replaces the generated effect. Run `npm run build` afterwards.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { CRIT_TESTS as TESTS, CRIT_CHOICES, CRIT_TURN_TESTS, CRIT_TURN_PENALTIES } from "./crit-tests-data.mjs";

const CRIT_TESTS = { ...TESTS, ...CRIT_CHOICES };

const DIR = path.join("src", "packs", "items");
const MODULE_ID = JSON.parse(fs.readFileSync("module.json", "utf8")).id;
const files = Object.fromEntries(fs.readdirSync(DIR).filter(f => f.endsWith(".json")).map(f => {
  const d = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  return [d._id, { file: f, doc: d }];
}));

const ALNUM = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
function stableId(seed) {
  const h = crypto.createHash("sha256").update(seed).digest();
  return Array.from(h.subarray(0, 16), b => ALNUM[b % ALNUM.length]).join("");
}

function action(a) {
  const [kind, ...rest] = a.split(":");
  const arg = rest.join(":");
  switch (kind) {
    case "cond": {
      const [key, n] = rest;
      return `await this.actor.addCondition(${JSON.stringify(key)}${n ? `, ${Number(n)}` : ""});`;
    }
    case "drop": return `await api.dropHeld(this, {where: ${JSON.stringify(rest[0])}${rest[1] === "keep2h" ? ", keepTwoHanded: true" : ""}});`;
    case "item": return `await api.addCoreItem(this, ${JSON.stringify(arg)});`;
    case "next": return `await api.nextTestPenalty(this, ${Number(arg)});`;
    case "note": return `await api.gmNote(this, ${JSON.stringify(arg)});`;
    case "dropchoose": return `await api.dropChosen(this);`;
    case "code": return arg;
    case "uncond": {
      const [key, n] = rest;
      return `await this.actor.removeCondition(${JSON.stringify(key)}${n ? `, ${Number(n)}` : ""});`;
    }
    case "stop": return `await api.stopTurnTests(this${arg ? `, ${JSON.stringify(arg)}` : ""});`;
    case "turnnote": return `await api.turnNote(this, ${JSON.stringify(arg)});`;
    case "penalty": {
      const [mod, ...flags] = rest;
      const opts = [`modifier: ${Number(mod)}`, `physical: ${flags.includes("physical")}`];
      if (flags.includes("halfmove")) opts.push("halveMove: true");
      const mv = flags.find(f => /^move-?\d+$/.test(f));
      if (mv) opts.push(`move: ${Number(mv.slice(4))}`, `label: ${JSON.stringify(`${Number(mv.slice(4)) > 0 ? "+" : ""}${Number(mv.slice(4))} M this turn`)}`);
      return `await api.turnPenalty(this, {${opts.join(", ")}});`;
    }
    case "ungrant": return `await api.removeGranted(this, ${JSON.stringify(rest[0])}${rest[1] === "any" ? `, "any"` : ""});`;
    default: throw new Error(`Unknown action ${a}`);
  }
}
const indent = (code, n) => code.split("\n").map(l => (l ? " ".repeat(n) + l : l)).join("\n");
const block = (list, n) => indent((list ?? []).map(action).join("\n"), n);

function testCall(t, fn = "rollCritTest") {
  const spec = {};
  for (const k of ["skill", "skills", "characteristic", "difficulty", "choice", "success", "failure", "title", "optional"]) if (t[k] !== undefined) spec[k] = t[k];
  return `await api.${fn}(this, ${JSON.stringify(spec).replace(/"(\w+)":/g, "$1: ").replace(/,(?=\w+: )/g, ", ")})`;
}

// A choice the victim makes on receipt: {prompt, after?, options: [{id, label, hint?, if?: "<js expr>", do: [actions]}]}
function choiceBlock(c) {
  const opts = c.options.map(o => `    { id: ${JSON.stringify(o.id)}, label: ${JSON.stringify(o.label)}${o.hint ? `, hint: ${JSON.stringify(o.hint)}` : ""}${o.if ? `, disabled: !(${o.if})` : ""} }`).join(",\n");
  let s = `{\n  const choice = await api.chooseCritOption(this, { prompt: ${JSON.stringify(c.prompt)}, options: [\n${opts}\n  ] });\n`;
  c.options.forEach((o, i) => {
    s += `  ${i ? "else if" : "if"} (choice === ${JSON.stringify(o.id)}) {\n${block(o.do, 4) || "    // nothing"}\n  }\n`;
  });
  return s + `}\n`;
}

function testBlock(t, fn) {
  let s = `{\n  const test = ${testCall(t, fn)};\n  if (test) {\n`;
  if (t.fail?.length || t.pass?.length) {
    s += `    if (test.failed) {\n${block(t.fail, 6) || "      // no further effect"}\n    }\n`;
    if (t.pass?.length) s += `    else {\n${block(t.pass, 6)}\n    }\n`;
  }
  if (t.always?.length) s += `${block(t.always, 4)}\n`;
  return s + `  }\n}\n`;
}

const TURN_LABEL = { startTurn: "Start of Turn", endTurn: "End of Turn" };
const TURN_WHEN = { startTurn: "at the start of each of the afflicted creature's turns", endTurn: "at the end of each of the afflicted creature's turns" };

// Recurring Test / roll in combat (CRIT_TURN_TESTS).
function buildTurnScript(spec) {
  let s = `// Expanded Criticals: ${spec.tests || spec.custom?.includes("turnTest") ? "Test" : "roll"} ${TURN_WHEN[spec.trigger]} in combat (generated by tools/crit-tests.mjs).\n`
    + `// warhammer-lib runs it once per round, on the client of the actor's active owner (its player if online, otherwise the GM).\n`
    + `const api = game.modules.get("${MODULE_ID}")?.api;\n`
    + `if (!api?.turnTest) return ui.notifications.error("Expanded Criticals is not active: resolve ${spec.name} by hand.");\n`
    + `if (!api.turnReady(this)) return;\n`;
  if (spec.each) s += spec.each.map(action).join("\n") + "\n";
  if (spec.chance) {
    s += `if (await api.chanceRoll(this, ${Number(spec.chance.pct)}, ${JSON.stringify(spec.chance.what)})) {\n${block(spec.chance.hit, 2)}\n}\n`;
    if (spec.chance.miss?.length) s += `else {\n${block(spec.chance.miss, 2)}\n}\n`;
  }
  for (const t of spec.tests ?? []) s += testBlock(t, "turnTest");
  if (spec.custom) s += spec.custom;
  return s.trimEnd();
}

function turnLabel(spec) {
  if (spec.tests) return `${TURN_LABEL[spec.trigger]}: ${spec.tests.map(t => t.skills?.join(" or ") ?? t.skill ?? (t.characteristic ? t.characteristic.toUpperCase() : "")).join(", ")} Test`;
  if (spec.chance) return `${TURN_LABEL[spec.trigger]}: ${spec.chance.pct}% ${spec.chance.what}`;
  return `${TURN_LABEL[spec.trigger]}: ${spec.name}`;
}

function buildScript(spec) {
  let s = `// Expanded Criticals: ${spec.tests || spec.custom ? "Test" : "choice"} prompted when this critical is received (generated by tools/crit-tests.mjs).\n`
    + `// ${spec.tests || spec.custom ? "Rolled by" : "Asked of"} the actor's player when the GM adds it (module setting "Who rolls critical Tests").\n`
    + `const api = game.modules.get("${MODULE_ID}")?.api;\n`
    + `if (!api?.rollCritTest) return ui.notifications.error("Expanded Criticals is not active: roll this critical's Test by hand.");\n`;
  if (spec.pre) s += (spec.pre.map(action).join("\n")) + "\n";
  for (const c of spec.choices ?? []) if (!c.after) s += choiceBlock(c);
  if (spec.custom) return s + spec.custom;
  for (const t of spec.tests ?? []) s += testBlock(t);
  for (const c of spec.choices ?? []) if (c.after) s += choiceBlock(c);
  return s.trimEnd();
}

const isTestScript = s => s.trigger === "immediate" && /setup(Skill|Characteristic)\(/.test(s.script ?? "");

let changed = 0;
for (const [id, spec] of Object.entries(CRIT_TESTS)) {
  const entry = files[id];
  if (!entry) throw new Error(`Item ${id} (${spec.name}) not found`);
  const item = entry.doc;
  if (item.name !== spec.name) throw new Error(`Item ${id}: name '${item.name}' != '${spec.name}'`);
  const before = JSON.stringify(item);
  const remove = new Set(spec.remove ?? []);

  // Keep the generated effect where it was, so the other generator (tools/grants.mjs) doesn't reorder it.
  const oldIdx = item.effects.findIndex(e => e.flags?.[MODULE_ID]?.critTest);
  const keepBefore = oldIdx < 0 ? null : item.effects.slice(0, oldIdx).filter(e => !remove.has(e.name)).length;
  item.effects = item.effects.filter(e => !e.flags?.[MODULE_ID]?.critTest && !remove.has(e.name)).filter(e => {
    const scripts = e.system?.scriptData ?? [];
    const kept = scripts.filter(s => !isTestScript(s));
    if (kept.length === scripts.length) return true;
    e.system.scriptData = kept;
    return kept.length > 0 || (e.system.changes ?? []).length > 0;
  });

  const effectId = stableId(`${id}-crit-test`);
  const template = JSON.parse(JSON.stringify(item.effects.find(e => e.system?.transferData) ?? files["MhSOwhgv20449EoO"].doc.effects[0]));
  const effect = {
    ...template,
    name: `${item.name} (${spec.tests || spec.custom ? "Test" : "Choice"})`,
    img: item.img,
    _id: effectId,
    disabled: false,
    description: "",
    statuses: [],
    duration: { value: null, units: "seconds", expiry: null, expired: false },
    transfer: true,
    flags: { wfrp4e: { manualEffectKeys: false }, [MODULE_ID]: { critTest: true } },
    _key: `!items.effects!${id}.${effectId}`
  };
  effect.system = JSON.parse(JSON.stringify(template.system));
  effect.system.transferData = { ...effect.system.transferData, type: "document", documentType: "Actor", avoidTest: { value: "none", opposed: false, prevention: true, reversed: false }, testIndependent: false, prompt: false };
  effect.system.changes = [];
  effect.system.scriptData = [{
    script: buildScript(spec),
    label: [spec.choices ? `Choice: ${spec.choices.map(c => c.options.map(o => o.label).join(" / ")).join("; ")}` : null,
      spec.tests ? `Test: ${spec.tests.map(t => t.skills?.join(" or ") ?? t.skill ?? t.characteristic).join(", ")}` : (spec.custom ? "Test" : null)].filter(Boolean).join(" | "),
    trigger: "immediate",
    options: { targeter: false, deleteEffect: true },
    async: false
  }];
  if (keepBefore === null) item.effects.push(effect);
  else item.effects.splice(Math.min(keepBefore, item.effects.length), 0, effect);

  if (JSON.stringify(item) !== before) {
    fs.writeFileSync(path.join(DIR, entry.file), JSON.stringify(item, null, 2) + "\n");
    changed++;
  }
}

// ---- recurring Tests in combat: "<Critical> (Start of Turn)" / "(End of Turn)" ----
let turnChanged = 0;
for (const [id, spec] of Object.entries(CRIT_TURN_TESTS)) {
  const entry = files[id];
  if (!entry) throw new Error(`Item ${id} (${spec.name}) not found`);
  const item = entry.doc;
  if (item.name !== spec.name) throw new Error(`Item ${id}: name '${item.name}' != '${spec.name}'`);
  if (!TURN_LABEL[spec.trigger]) throw new Error(`${spec.name}: trigger must be startTurn or endTurn`);
  const before = JSON.stringify(item);
  const remove = new Set(spec.remove ?? []);
  const oldIdx = item.effects.findIndex(e => e.flags?.[MODULE_ID]?.critTurn);
  const keepBefore = oldIdx < 0 ? null : item.effects.slice(0, oldIdx).filter(e => !remove.has(e.name)).length;
  item.effects = item.effects.filter(e => !e.flags?.[MODULE_ID]?.critTurn && !remove.has(e.name));

  const effectId = stableId(`${id}-crit-turn`);
  const template = JSON.parse(JSON.stringify(item.effects.find(e => e.system?.transferData) ?? files["MhSOwhgv20449EoO"].doc.effects[0]));
  const effect = {
    ...template,
    name: `${item.name} (${TURN_LABEL[spec.trigger]})`,
    img: item.img,
    _id: effectId,
    disabled: false,
    description: "",
    statuses: [],
    duration: { value: null, units: "seconds", expiry: null, expired: false },
    transfer: true,
    flags: { wfrp4e: { manualEffectKeys: false }, [MODULE_ID]: { critTurn: true } },
    _key: `!items.effects!${id}.${effectId}`
  };
  effect.system = JSON.parse(JSON.stringify(template.system));
  effect.system.transferData = { ...effect.system.transferData, type: "document", documentType: "Actor", avoidTest: { value: "none", opposed: false, prevention: true, reversed: false }, testIndependent: false, prompt: false };
  effect.system.changes = [];
  effect.system.scriptData = [{
    script: buildTurnScript(spec),
    label: turnLabel(spec),
    trigger: spec.trigger,
    options: { targeter: false, deleteEffect: false },
    async: true
  }];
  if (keepBefore === null) item.effects.push(effect);
  else item.effects.splice(Math.min(keepBefore, item.effects.length), 0, effect);

  if (JSON.stringify(item) !== before) {
    fs.writeFileSync(path.join(DIR, entry.file), JSON.stringify(item, null, 2) + "\n");
    turnChanged++;
  }
}

// ---- short penalties: "<Critical> (-10)" until the end / beginning of the next turn ----
let penChanged = 0;
const UNTIL = { endTurn: "until the end of your next turn", startTurn: "until the beginning of your next turn" };
const SCOPE = { all: "Tests", arm: "Tests using that arm", hand: "Tests using that hand" };
for (const [id, spec] of Object.entries(CRIT_TURN_PENALTIES)) {
  const entry = files[id];
  if (!entry) throw new Error(`Item ${id} (${spec.name}) not found`);
  const item = entry.doc;
  if (item.name !== spec.name) throw new Error(`Item ${id}: name '${item.name}' != '${spec.name}'`);
  if (!UNTIL[spec.until] || !SCOPE[spec.scope]) throw new Error(`${spec.name}: bad until/scope`);
  const before = JSON.stringify(item);
  const remove = new Set(spec.remove ?? []);
  const oldIdx = item.effects.findIndex(e => e.flags?.[MODULE_ID]?.critTurnPenalty || remove.has(e.name));
  item.effects = item.effects.filter(e => !e.flags?.[MODULE_ID]?.critTurnPenalty && !remove.has(e.name));
  const effectId = stableId(`${id}-crit-turn-penalty`);
  const template = JSON.parse(JSON.stringify(item.effects.find(e => e.system?.transferData) ?? files["MhSOwhgv20449EoO"].doc.effects[0]));
  const label = `${spec.mod} to ${SCOPE[spec.scope]} ${UNTIL[spec.until]}`;
  const effect = {
    ...template,
    name: `${item.name} (${spec.mod})`,
    img: item.img,
    _id: effectId,
    disabled: false,
    description: "",
    statuses: [],
    duration: { value: null, units: "seconds", expiry: null, expired: false },
    transfer: true,
    flags: { wfrp4e: { manualEffectKeys: false }, [MODULE_ID]: { critTurnPenalty: true } },
    _key: `!items.effects!${id}.${effectId}`
  };
  effect.system = JSON.parse(JSON.stringify(template.system));
  effect.system.transferData = { ...effect.system.transferData, type: "document", documentType: "Actor", avoidTest: { value: "none", opposed: false, prevention: true, reversed: false }, testIndependent: false, prompt: false };
  effect.system.changes = [];
  effect.system.scriptData = [
    { script: `args.fields.modifier += ${Number(spec.mod)};`, label: `${item.name}: ${label}`, trigger: "dialog",
      options: { targeter: false, defending: false, hideScript: "", activateScript: spec.scope === "all" ? "return true;" : "", submissionScript: "", deleteEffect: false }, async: false },
    { script: `// Expanded Criticals (generated by tools/crit-tests.mjs): the penalty lasts ${UNTIL[spec.until]}.\n// Runs on the client of the actor's active owner; removes this effect, not the critical.\nawait this.effect.delete();`,
      label: `Ends ${UNTIL[spec.until].replace("your", "the")}`, trigger: spec.until, options: { targeter: false, deleteEffect: false }, async: true }
  ];
  if (oldIdx < 0) item.effects.push(effect);
  else item.effects.splice(Math.min(oldIdx, item.effects.length), 0, effect);
  if (JSON.stringify(item) !== before) {
    fs.writeFileSync(path.join(DIR, entry.file), JSON.stringify(item, null, 2) + "\n");
    penChanged++;
  }
}
console.log(`crit-tests: ${Object.keys(CRIT_TESTS).length} criticals, ${changed} file(s) changed; ${Object.keys(CRIT_TURN_TESTS).length} recurring, ${turnChanged} file(s) changed; ${Object.keys(CRIT_TURN_PENALTIES).length} short penalties, ${penChanged} file(s) changed`);
