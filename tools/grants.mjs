// Apply tools/grants-data.mjs to the item JSON sources: each spec becomes one immediate effect that
// adds the core injury/disease when the critical is received (or rewrites an existing effect for `fix`).
// Idempotent: re-running replaces the generated effects. Run `npm run build` afterwards.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { GRANTS, CORE, CORE_NAMES } from "./grants-data.mjs";

const DIR = path.join("src", "packs", "items");
const MODULE_ID = JSON.parse(fs.readFileSync("module.json", "utf8")).id;
const files = Object.fromEntries(fs.readdirSync(DIR).filter(f => f.endsWith(".json")).map(f => {
  const d = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  return [d._id, { file: f, doc: d }];
}));

const ALNUM = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
const stableId = seed => Array.from(crypto.createHash("sha256").update(seed).digest().subarray(0, 16), b => ALNUM[b % ALNUM.length]).join("");
const J = JSON.stringify;

const PREAMBLE = `const grant = async (id, value, key = this.item.system.location?.key) => {
  const item = await fromUuid(\`Compendium.wfrp4e-core.items.Item.\${id}\`);
  if (!item) return ui.notifications.error(\`Expanded Criticals: core item \${id} not found (is WFRP4e Core active?). Add it by hand.\`);
  const data = item.toObject();
  // skipLocationValue keeps our display value ("5 Teeth", "Right Hand", "Nose") instead of the one derived from the key ("Head")
  let skipLocationValue = false;
  if (data.type === "injury" && data.system.location) {
    if (key) data.system.location.key = key;
    if (value) data.system.location.value = value;
    skipLocationValue = !!value || ["Teeth", "Nose", "Tongue", "Eye", "Ear"].includes(data.system.location.value);
  }
  return this.actor.createEmbeddedDocuments("Item", [data], {skipLocationValue});
};
const rollCount = async (formula, div = 1, add = 0, flavor) => {
  const roll = await new Roll(formula).evaluate({allowInteractive: false});
  if (flavor && /d/i.test(formula)) await roll.toMessage(this.script.getChatData({flavor}));
  return Math.max(1, Math.ceil(roll.total / div) + add);
};`;
const SIDE = `const s = this.item.system.location?.key?.[0] === "l" ? "l" : "r";
const side = s === "l" ? "Left" : "Right";`;

function label(g) {
  if (g.name) return g.name;
  if (g.core) return CORE_NAMES[g.core];
  if (g.fingers) return "Amputated Fingers";
  if (g.toes) return "Amputated Toes";
  if (g.teeth) return "Amputated Teeth";
  throw new Error(`Grant without a name: ${J(g)}`);
}

function body(g) {
  if (g.code) return g.code;
  if (g.core) {
    if (!CORE_NAMES[g.core]) throw new Error(`Unknown core id ${g.core}`);
    return (g.keys ?? [undefined]).map(k => `await grant(${J(g.core)}${g.value || k ? `, ${J(g.value ?? null)}` : ""}${k ? `, ${J(k)}` : ""});`).join("\n");
  }
  const count = (f, flavor) => `const n = await rollCount(${J(f)}, ${g.div ?? 1}, ${g.add ?? 0}, ${J(flavor)});`;
  if (g.fingers) return `${count(g.fingers, "Fingers Lost")}\n${SIDE}\n`
    + (g.hand5 ? `if (n >= 5) await grant(${J(CORE.ampHand)}, null, s + "Arm"); // five fingers: the entire hand\nelse ` : "")
    + `for (let i = 0; i < n; i++) await grant(${J(CORE.ampFinger)}, \`\${side} Hand\`, s + "Hand");`;
  if (g.toes) return `${count(g.toes, "Toes Lost")}\n${SIDE}\nawait grant(${J(CORE.ampToe)}, \`\${n} \${side} Toe\${n > 1 ? "s" : ""}\`, s + "Toe");`;
  if (g.teeth) return `${count(g.teeth, "Teeth Lost")}\nawait grant(${J(CORE.ampTeeth)}, \`\${n} Teeth\`);`;
  throw new Error(`Bad grant spec ${J(g)}`);
}

const script = (g, critName) => `// Expanded Criticals: ${critName} grants ${label(g)} (generated by tools/grants.mjs).\n${PREAMBLE}\n${body(g)}`;

let changed = 0, added = 0, fixed = 0;
for (const [id, spec] of Object.entries(GRANTS)) {
  const entry = files[id];
  if (!entry) throw new Error(`Item ${id} (${spec.name}) not found`);
  const item = entry.doc;
  if (item.name !== spec.name) throw new Error(`Item ${id}: name '${item.name}' != '${spec.name}'`);
  const before = J(item);
  // Generated effects go back where they were, so tools/crit-tests.mjs and this tool don't reorder each other.
  const oldIdx = item.effects.findIndex(e => e.flags?.[MODULE_ID]?.grant);
  item.effects = item.effects.filter(e => !e.flags?.[MODULE_ID]?.grant);
  let insertAt = oldIdx < 0 ? item.effects.length : oldIdx;
  const template = item.effects.find(e => e.system?.transferData) ?? files["MhSOwhgv20449EoO"].doc.effects[0];

  spec.grants.forEach((g, i) => {
    const name = label(g);
    const scriptData = {
      script: script(g, item.name),
      label: name,
      trigger: "immediate",
      options: { targeter: false, defending: false, hideScript: "", activateScript: "", submissionScript: "", deleteEffect: true, runIfDisabled: false, showDuplicates: false },
      async: false
    };
    if (g.fix) {
      const e = item.effects.find(e => e._id === g.fix);
      if (!e) throw new Error(`${item.name}: effect ${g.fix} to fix not found`);
      e.name = name;
      e.system.scriptData = [scriptData];
      e.system.changes = [];
      e.flags = { ...(e.flags ?? {}), [MODULE_ID]: { ...(e.flags?.[MODULE_ID] ?? {}), grantFix: true } };
      fixed++;
      return;
    }
    const effectId = stableId(`${id}-grant-${i}`);
    const effect = JSON.parse(J(template));
    Object.assign(effect, {
      name, img: item.img, _id: effectId, disabled: false, description: "", statuses: [], transfer: true, origin: null,
      duration: { value: null, units: "seconds", expiry: null, expired: false },
      flags: { wfrp4e: { manualEffectKeys: false }, [MODULE_ID]: { grant: true } },
      _key: `!items.effects!${id}.${effectId}`
    });
    effect._stats = { ...(effect._stats ?? {}), compendiumSource: null, duplicateSource: null };
    effect.system.transferData = { ...effect.system.transferData, type: "document", documentType: "Actor", avoidTest: { value: "none", opposed: false, prevention: true, reversed: false }, testIndependent: false, prompt: false };
    effect.system.changes = [];
    effect.system.scriptData = [scriptData];
    item.effects.splice(insertAt++, 0, effect);
    added++;
  });

  if (J(item) !== before) {
    fs.writeFileSync(path.join(DIR, entry.file), J(item, null, 2) + "\n");
    changed++;
  }
}
console.log(`grants: ${Object.keys(GRANTS).length} criticals, ${added} added + ${fixed} fixed effect(s), ${changed} file(s) changed`);
